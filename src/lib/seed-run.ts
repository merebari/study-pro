function skillCategory(subject: string): string {
  const s = subject.toLowerCase();
  if (/(math|reasoning)/.test(s)) return "math";
  if (/(english|language|french|literature)/.test(s)) return "language";
  if (/(science|biology|chemistry|physics|agric|health|physical|technology|computer|data|animal)/.test(s)) return "science";
  if (/(social|civic|government|geography|history|religious|studies)/.test(s)) return "humanities";
  if (/(commerce|accounting|economics|marketing|business)/.test(s)) return "business";
  return "default";
}

function buildObjectives(title: string, subjectName: string, classNames: string): string[] {
  const verbs = SKILL_VERBS[skillCategory(subjectName)];
  const h = hash(title + subjectName);
  const core = title.replace(/:$/, "");
  const objs: string[] = [];
  const pick = (i: number) => verbs[(h + i * 7) % verbs.length];
  for (let i = 0; i < 3; i++) {
    const v = pick(i);
    objs.push(v[1] ? `${v[0]}‘${core}’${v[1]}` : `${v[0]} ${core.toLowerCase()}`);
  }
  objs.push(`Score confidently on ${core} questions set at ${classNames.split("·")[0].trim()} level`);
  return objs;
}

function buildOverview(t: TopicDef, subject: SubjectDef, classNames: string, bandShortName: string): string {
  const gloss = glossFor(t.t);
  const h = hash(t.t);
  const openers = [
    `${t.t} is one of the most important ${subject.name} stops in`,
    `Welcome to ${t.t} — a core ${subject.name} topic taught across`,
    `${t.t} sits at the heart of ${bandShortName} ${subject.name}, covered in`,
    `Few ${subject.name} ideas show up as often as ${t.t}, taught in`,
  ];
  const opener = `${openers[h % openers.length]} ${classNames}.`;
  const mid = gloss
    ? ` ${gloss.charAt(0).toUpperCase()}${gloss.slice(1)}.`
    : ` ${subject.blurb.split("—")[0].replace(/\.$/, "")} — here, that means mastering ${t.t.toLowerCase()} class by class.`;
  const closer =
    h % 3 === 0
      ? ` Work through the class focus notes below, tick off the objectives, then test yourself with practice questions.`
      : h % 3 === 1
        ? ` Start with the learning objectives, study the focus for your class and finish with a quick self-test.`
        : ` The notes below break it down by class so you always know exactly what this level expects.`;
  return t.d ?? `${opener}${mid}${closer}`;
}

function buildKeyPoints(t: TopicDef): string[] {
  const points: string[] = [];
  const focuses = Object.values(t.focus ?? {}).filter(Boolean);
  for (const f of focuses.slice(0, 4)) points.push(f.endsWith(".") ? f : `${f}.`);
  const core = t.t.replace(/:$/, "");
  points.push(`Master the vocabulary of ${core.toLowerCase()} — exam questions repeat the same key terms.`);
  points.push(`Practise ${core.toLowerCase()} with past questions from Common Entrance, BECE or WAEC/NECO as appropriate.`);
  return points.slice(0, 6);
}

function buildExamTip(title: string, subject: SubjectDef): string {
  const cat = skillCategory(subject.name);
  const band = subject.band;
  const exam = band === "PRI" ? "Common Entrance" : band === "JSS" ? "BECE" : "WAEC/NECO";
  if (cat === "math")
    return `In ${exam}, ${title.toLowerCase()} questions reward method marks: write every step, box your final answer and re-check units.`;
  if (cat === "language")
    return `${exam} markers reward accuracy — leave 2 minutes to read your ${title.toLowerCase()} answers aloud in your head and fix slips.`;
  if (cat === "science")
    return `${exam} loves labelled diagrams and precise terms here. Learn the definition exactly, then practise describing the process in your own words.`;
  if (cat === "business")
    return `Definitions + Nigerian examples + correct layouts earn the marks for ${title.toLowerCase()} in ${exam}. Practise formats until they are automatic.`;
  if (cat === "humanities")
    return `For ${exam}, answer ${title.toLowerCase()} with a clear definition, explained points and one Nigerian example each — structure wins half the marks.`;
  return `Use flashcards for the key terms of ${title.toLowerCase()} and attempt ${exam} past questions on this topic weekly.`;
}

function termFor(index: number, total: number): 1 | 2 | 3 {
  const third = Math.max(1, Math.ceil(total / 3));
  if (index < third) return 1;
  if (index < third * 2) return 2;
  return 3;
}

/* ── The seed itself (batched inserts — serverless-friendly) ── */
export async function runSeed(db: SeedDb) {
  await db.delete(schema.questions);
  await db.delete(schema.topicClasses);
  await db.delete(schema.topics);
  await db.delete(schema.classSubjects);
  await db.delete(schema.subjects);
  await db.delete(schema.classes);
  await db.delete(schema.bands);

  const bandIds = new Map<string, number>();
  const bandRows = await db
    .insert(schema.bands)
    .values(BANDS.map((b, i) => ({ code: b.code, name: b.name, short: b.short, blurb: b.blurb, position: i })))
    .returning({ id: schema.bands.id, code: schema.bands.code });
  for (const b of bandRows) bandIds.set(b.code, b.id);

  const classIds = new Map<string, number>();
  const classRows = await db
    .insert(schema.classes)
    .values(
      CLASSES.map((c) => ({
        bandId: bandIds.get(c.band)!,
        code: c.code,
        slug: c.slug,
        name: c.name,
        stage: c.stage,
        tagline: c.tagline,
        description: c.description,
        exam: c.exam ?? null,
        examDetail: c.examDetail ?? null,
      }))
    )
    .returning({ id: schema.classes.id, code: schema.classes.code });
  for (const c of classRows) classIds.set(c.code, c.id);

  const classByCode = new Map(CLASSES.map((c) => [c.code, c]));
  const classNameList = (codes: string[]) => codes.map((c) => classByCode.get(c)!.name).join(" · ");
  const richByKey = new Map(RICH_BATCHES.map((r) => [`${r.subject}::${r.band}`, r]));

  const topicIdBySubjectTitle = new Map<string, number>();
  const subjectIdByNameBand = new Map<string, number>();
  let topicCount = 0;
  let richCount = 0;
  let focusCount = 0;

  for (const subject of ALL_SUBJECTS) {
    const batch = richByKey.get(`${subject.name}::${subject.band}`);
    const topicDefs: TopicDef[] = [...(batch?.additions ?? []), ...subject.topics];

    const [subj] = await db
      .insert(schema.subjects)
      .values({
        bandId: bandIds.get(subject.band)!,
        name: subject.name,
        slug: `${slugify(subject.name)}-${subject.band.toLowerCase()}`,
        icon: subject.icon,
        color: subject.color,
        blurb: subject.blurb,
      })
      .returning({ id: schema.subjects.id });
    subjectIdByNameBand.set(`${subject.name}::${subject.band}`, subj.id);

    await db.insert(schema.classSubjects).values(
      subject.classes.map((code, i) => ({ classId: classIds.get(code)!, subjectId: subj.id, position: i }))
    );

    const bandShortName = BANDS.find((b) => b.code === subject.band)!.short;
    const seen = new Set<string>();

    const topicValues = topicDefs.map((t, i) => {
      const rich: RichTopic | undefined = batch?.notes[t.t];
      if (rich) richCount++;
      let slug = slugify(t.t);
      while (seen.has(slug)) slug = `${slug}-2`;
      seen.add(slug);
      const keyPoints = buildKeyPoints(t);
      const g = glossFor(t.t);
      const codes = t.classes ?? subject.classes;
      return {
        def: t,
        codes,
        values: {
          subjectId: subj.id,
          slug,
          title: t.t,
          term: rich?.term ?? t.term ?? termFor(i, topicDefs.length),
          overview: rich?.explain?.[0] ?? buildOverview(t, subject, classNameList(codes), bandShortName),
          objectives: buildObjectives(t.t, subject.name, classNameList(codes)),
          keyPoints,
          explanation: rich?.explain ?? [],
          examples: rich?.examples ?? [],
          keyTerms:
            rich?.keyTerms ??
            [
              ...(g ? [{ term: t.t, def: `${g}.` }] : []),
              ...Object.entries(t.focus ?? {})
                .slice(0, 2)
                .map(([code, f]) => ({
                  term: `${t.t} in ${classByCode.get(code)!.name}`,
                  def: f.endsWith(".") ? f : `${f}.`,
                })),
            ],
          summary: rich?.summary ?? keyPoints,
          examTip: buildExamTip(t.t, subject),
          gloss: g,
          position: i,
        } satisfies typeof schema.topics.$inferInsert,
      };
    });

    const inserted = await db
      .insert(schema.topics)
      .values(topicValues.map((v) => v.values))
      .returning({ id: schema.topics.id, slug: schema.topics.slug });

    const idBySlug = new Map(inserted.map((r) => [r.slug, r.id]));
    const tcValues: Array<typeof schema.topicClasses.$inferInsert> = [];
    for (const tv of topicValues) {
      const topicId = idBySlug.get(tv.values.slug)!;
      topicIdBySubjectTitle.set(`${subj.id}::${tv.def.t}`, topicId);
      topicCount++;
      for (const code of tv.codes) {
        tcValues.push({
          topicId,
          classId: classIds.get(code)!,
          focus: tv.def.focus?.[code] ?? null,
        });
        focusCount++;
      }
    }
    await db.insert(schema.topicClasses).values(tcValues);
  }

  // Questions (regular practice + past questions + batch quizzes)
  const ALL_QS = [...QUESTIONS, ...PAST_QUESTIONS, ...P1_MATH_QUIZ];
  await db.insert(schema.questions).values(
    ALL_QS.flatMap((q) => {
      const subjectId = subjectIdByNameBand.get(`${q.subject}::${q.band}`);
      if (!subjectId) return [];
      return [
        {
          subjectId,
          classId: q.classCode ? classIds.get(q.classCode)! : null,
          topicId: q.topic ? topicIdBySubjectTitle.get(`${subjectId}::${q.topic}`) ?? null : null,
          question: q.q,
          options: q.options,
          answerIndex: q.answer,
          explanation: q.explain,
          level: q.level,
          exam: q.exam ?? null,
          year: q.year ?? null,
        } satisfies typeof schema.questions.$inferInsert,
      ];
    })
  );

  return { topics: topicCount, focusNotes: focusCount, rich: richCount, questions: ALL_QS.length };
}
